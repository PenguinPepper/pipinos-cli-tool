import fs from 'fs/promises';
import path from 'path';

export async function writeOutputs(output, outputDir) {
    await fs.mkdir(outputDir, { recursive: true });

    const flashcardsPath = path.join(outputDir, 'flashcards.md');
    const diagramPath = path.join(outputDir, 'diagram.mmd');
    const cheatsheetPath = path.join(outputDir, 'cheatsheet.md');

    await Promise.all([
        fs.writeFile(flashcardsPath, renderFlashcards(output.flashcards), 'utf-8'),
        fs.writeFile(diagramPath, output.diagram, 'utf-8'),
        fs.writeFile(cheatsheetPath, output.cheatsheet, 'utf-8'),
    ]);

    return { flashcardsPath, diagramPath, cheatsheetPath };
}

function renderFlashcards(cards) {
    const lines = [];

    lines.push('# Flashcards');
    lines.push('');
    lines.push('> Auto-generated by **sky-cli**. Each card has a question and answer — great for spaced repetition.');
    lines.push('');

    const grouped = groupBy(cards, (c) => c.category);

    const categoryLabels = {
        architecture: '🏗 Architecture',
        setup: '⚙️ Setup & Configuration',
        dependency: '📦 Dependencies',
        concept: '💡 Concepts',
        workflow: '🔄 Workflow',
    };

    for (const [cat, catCards] of Object.entries(grouped)) {
        const label = categoryLabels[cat] ?? cat;
        lines.push(`## ${label}`);
        lines.push('');

        for (let i = 0; i < catCards.length; i++) {
            const card = catCards[i];
            lines.push(`### Card ${i + 1}`);
            lines.push('');
            lines.push(`**Q:** ${card.question}`);
            lines.push('');
            lines.push(`**A:** ${card.answer}`);
            lines.push('');
            lines.push('---');
            lines.push('');
        }
    }

    lines.push(`*${cards.length} cards total*`);
    return lines.join('\n');
}

function groupBy(arr, key) {
    return arr.reduce((acc, item) => {
        const k = key(item);
        (acc[k] ??= []).push(item);
        return acc;
    }, {});
}